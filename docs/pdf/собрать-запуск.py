def img(name):
    p = os.path.join(SHOTS, name + "-crop.png")
    return "data:image/png;base64," + base64.b64encode(open(p, "rb").read()).decode()


def fig(name, alt, cap):
    return (f'<figure><img src="{img(name)}" alt="{alt}">'
            f'<figcaption>{cap}</figcaption></figure>')


def steps(items):
    return '<ol class="steps">' + "".join(f"<li>{i}</li>" for i in items) + "</ol>"


def table(head, rows):
    h = "".join(f"<th>{c}</th>" for c in head)
    b = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="tw"><table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table></div>'


def note(text):
    return f'<div class="note"><p>{text}</p></div>'


def xlsheet(filename, caption, first=0, last=None):
    """Лист Excel как он выглядит в редакторе: буквы колонок, номера строк.

    Собирается из настоящего образцового файла — значит, показанное
    в инструкции ровно то, что система принимает. first и last вырезают
    диапазон колонок: широкий план закупок в страницу целиком не влезает,
    поэтому показывается двумя кусками с сохранением букв колонок.
    """
    from openpyxl import load_workbook
    ws = load_workbook(os.path.join(D, "образцы", filename), data_only=True).active
    rows = [list(r)[first:last] for r in ws.iter_rows(values_only=True)]
    width = max(len(r) for r in rows)
    letters = "".join(f"<th>{chr(65 + first + i)}</th>" for i in range(width))
    body = ""
    for n, row in enumerate(rows, start=1):
        cells = ""
        for v in list(row) + [None] * (width - len(row)):
            if v is None or v == "":
                cells += '<td class="empty"></td>'
            elif isinstance(v, (int, float)):
                cells += f'<td class="num">{v}</td>'
            else:
                cells += f"<td>{v}</td>"
        body += f"<tr><th>{n}</th>{cells}</tr>"
    return (f'<div class="xl"><table><thead><tr><th></th>{letters}</tr></thead>'
            f"<tbody>{body}</tbody></table></div>"
            f'<p class="xlcap">{caption}</p>')



# -*- coding: utf-8 -*-
"""Сборка инструкций по ролям из общего шаблона."""
import io, os, base64

D = os.path.dirname(os.path.abspath(__file__))
SHOTS = os.path.join(D, 'all')

CSS = io.open(os.path.join(D, 'shared.css'), encoding='utf-8').read()

def img(role, name):
    p = os.path.join(SHOTS, role, name + '-crop.png')
    return 'data:image/png;base64,' + base64.b64encode(open(p, 'rb').read()).decode()

def fig(role, name, alt, cap):
    return (f'<figure><img src="{img(role, name)}" alt="{alt}">'
            f'<figcaption>{cap}</figcaption></figure>')

def steps(items):
    return '<ol class="steps">' + ''.join(f'<li>{i}</li>' for i in items) + '</ol>'

def table(head, rows):
    h = ''.join(f'<th>{c}</th>' for c in head)
    b = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<div class="tw"><table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table></div>'

def note(text):
    return f'<div class="note"><p>{text}</p></div>'

def section(eyebrow, title, lede, body):
    return (f'<hr class="rule"><section><div class="eyebrow">{eyebrow}</div>'
            f'<h2>{title}</h2>' + (f'<p class="lede">{lede}</p>' if lede else '') + body + '</section>')

OK = '<span class="pill ok">менять</span>'
NO = '<span class="pill no">не видно</span>'

def build(role, title, subtitle, brand, sections):
    body = ''.join(sections)
    return f'''<title>{title}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bitter:wght@600;700&family=Manrope:wght@400;500;600;700&family=JetBrains+Mono:wght@500&display=swap">
<style>{CSS}</style>
<header class="top"><div class="wrap">
  <div class="brand">КазДемеу · {brand}</div>
  <h1>{title}</h1>
  <p>{subtitle}</p>
  <a class="addr" href="https://open-test.ektu.kz">open-test.ektu.kz</a>
</div></header>
<div class="wrap">{body}</div>'''

